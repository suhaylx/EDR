package edr

import (
	"context"
	"crypto/rand"
	"crypto/sha256"
	"database/sql"
	"encoding/hex"
	"errors"
	"fmt"
	"strings"
)

// IssuedEnrollmentChallenge is returned ONLY to a pinned, authenticated
// issuer. The plain secret must be delivered out-of-band to the correct
// endpoint over a separately approved secure provisioning channel.
// The database stores only its SHA-256 digest.
type IssuedEnrollmentChallenge struct {
	ChallengeID     string
	ChallengeSecret [32]byte
	TTLSeconds      int
}

var ErrChallengeIssueInvalid = errors.New("invalid challenge issuance request")
var ErrChallengeIssueUnavailable = errors.New("enrollment challenge issuance unavailable")

type EnrollmentChallengeIssuer interface {
	IssueEnrollmentChallenge(context.Context, string, string, string, int) (*IssuedEnrollmentChallenge, error)
}

type PostgresEnrollmentChallengeIssuer struct{ DB *sql.DB }

const issueEnrollmentChallengeSQL = `SELECT edr_issue_enrollment_challenge(
	$1::uuid,$2,$3,$4,$5,$6)`

// IssueEnrollmentChallenge cryptographically generates both the UUIDv4 and
// the 32-byte secret, then atomically persists only the hash. A nil challenge
// with nil error means the agent/tenant is ineligible or a challenge already
// exists. A DB failure is not interpreted as approval.
func (s PostgresEnrollmentChallengeIssuer) IssueEnrollmentChallenge(
	ctx context.Context, tenantID, agentID, actorID string, ttlSeconds int,
) (*IssuedEnrollmentChallenge, error) {
	if !validQueueIdentity(tenantID, agentID) ||
		len(actorID) < 1 || len(actorID) > 256 ||
		strings.TrimSpace(actorID) != actorID ||
		ttlSeconds < 60 || ttlSeconds > 600 {
		return nil, ErrChallengeIssueInvalid
	}
	if s.DB == nil {
		return nil, ErrChallengeIssueUnavailable
	}
	var rawID [16]byte
	var secret [32]byte
	if _, err := rand.Read(rawID[:]); err != nil {
		return nil, ErrChallengeIssueUnavailable
	}
	if _, err := rand.Read(secret[:]); err != nil {
		return nil, ErrChallengeIssueUnavailable
	}
	// RFC 4122 UUIDv4, generated by crypto/rand.
	rawID[6] = (rawID[6] & 0x0f) | 0x40
	rawID[8] = (rawID[8] & 0x3f) | 0x80
	hexID := hex.EncodeToString(rawID[:])
	id := fmt.Sprintf("%s-%s-%s-%s-%s",
		hexID[:8], hexID[8:12], hexID[12:16], hexID[16:20], hexID[20:])
	digest := sha256.Sum256(secret[:])
	var created bool
	err := s.DB.QueryRowContext(ctx, issueEnrollmentChallengeSQL,
		id, tenantID, agentID, digest[:], ttlSeconds, actorID).Scan(&created)
	if err != nil {
		clear(secret[:])
		return nil, ErrChallengeIssueUnavailable
	}
	if !created {
		clear(secret[:])
		return nil, nil
	}
	return &IssuedEnrollmentChallenge{
		ChallengeID: id, ChallengeSecret: secret, TTLSeconds: ttlSeconds,
	}, nil
}
